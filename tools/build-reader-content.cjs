const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data/reader-markers-v0.1.json'), 'utf8'));
const output = '// Generated by tools/build-reader-content.cjs; edit the JSON source.\n' +
  'globalThis.ReaderContent = ' + JSON.stringify(data, null, 2) + ';\n';
const target = path.join(root, 'src/reader-content.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw Error('Reader content is stale');
} else fs.writeFileSync(target, output);
